def resync(raw_dicts: List[Dict], debug: bool = False) -> GFREResult:
    """
    One-call convenience: raw fill dicts -> GFREResult.

    Converts raw parser dicts to FillRecords and runs all 5 GFRE stages.

    Example
    -------
        from trading_platform.services.ghost_fill_engine import resync
        from trading_platform.services.binary_log_parser import _parse_file_nitro

        raw, _ = _parse_file_nitro("dataset/TradeActivityLog_2026-06-10_UTC.TM_7.data")
        result = resync(raw)
        print(result.summary())
        for t in result.trades:
            print(t)
    """
    engine = GhostFillEngine(debug=debug)
    fills  = GhostFillEngine.from_dicts(raw_dicts)
    return engine.process(fills)
