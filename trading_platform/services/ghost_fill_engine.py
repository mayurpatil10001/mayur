def classify_fill(fill: FillRecord) -> bool:
    """
    Stage 1 -- Tag-Validation Filter.

    Returns True if the fill is a ghost (should be dropped).

    Rules
    -----
    1. qty==1: Always retain (1-lot exemption -- single-contract fills
       are almost always legitimate stop-outs or 1-lot strategy entries).
    2. EOD window (16:55-17:05 NY): Always retain (session flattenings
       often lack tags).
    3. Trading Evaluator signature in message:
       - CLOSE flag: Always retain.  SC's Trade Evaluator processes
         limit-target and stop-loss exits WITHOUT propagating the
         strategy's Tag 0x82 note.  These are real exits, not ghosts.
         Empirical evidence: both large cascade swings (Jun-23 -$10,620
         and Jul-02 -$35,835) were caused by dropping CLOSE TE fills.
       - OPEN flag with no strategy tag: ghost.
       - OPEN/unknown with strategy tag: retain.
    4. Non-Evaluator fills:
       - CLOSE (exit): Always retain.
       - OPEN/unknown with no tag: ghost.
    """
    if fill.quantity == 1:
        return False
    if _is_eod_exempt(fill.timestamp):
        return False

    msg_l        = fill.msgtxt.lower()
    is_evaluator = EVALUATOR_FILL_SIGNATURE in msg_l

    if is_evaluator:
        # FIX v2: CLOSE exits from TE are real exits — always retain.
        # Only OPEN TE fills that lack a strategy tag are ghosts.
        if fill.open_close == "CLOSE":
            return False
        return not _has_strategy_tag(fill.note, fill.msgtxt)

    if fill.open_close == "CLOSE":
        return False
    return not _has_strategy_tag(fill.note, fill.msgtxt)


# ---------------------------------------------------------------------------
# Stage 2: Adaptive Bypass Detection
# ---------------------------------------------------------------------------

def _compute_note_rate(fills: List[FillRecord]) -> Tuple[float, bool]:
    """
    Stage 2 -- Adaptive Bypass Detection.

    Compute note coverage rate. If <25% of fills have strategy notes
    and there are >5 fills total, activate bypass mode (no-note account).

    Returns (note_rate, bypass_active).
    """
    total = len(fills)
    if total == 0:
        return 1.0, False
    with_notes = sum(1 for f in fills if f.note.strip())
    rate   = with_notes / total
    bypass = rate < ADAPTIVE_NOTE_RATE_THRESHOLD and total > ADAPTIVE_MIN_FILLS
    return rate, bypass


# ---------------------------------------------------------------------------
# Stage 3: Per-Batch Deduplication
# ---------------------------------------------------------------------------

def _dedup_fills(fills: List[FillRecord], bucket_ms: int = 250) -> List[FillRecord]:
    """
    Stage 3 -- Per-Batch Deduplication.

    Sierra Chart may emit the same fill record within ~460ms. Collapse
    duplicates using a composite time-bucket key. The richer record
    (one with a strategy note, or one NOT flagged as ghost) is kept.

    Parameters
    ----------
    fills     : Fills sorted by ts_val ascending.
    bucket_ms : Bucket width in milliseconds (default 250ms).
    """
    bucket_sec = bucket_ms / 1000.0
    seen: Dict[tuple, FillRecord] = {}
    for f in fills:
        ts_bucket = round(f.ts_val / bucket_sec) * bucket_sec
        key = (ts_bucket, f.price, f.side, f.quantity, f.account, f.order_id)
        if key not in seen:
            seen[key] = f
        else:
            ex = seen[key]
            if not ex.note.strip() and f.note.strip():
                seen[key] = f
            elif ex.suggests_ghost and not f.suggests_ghost:
                seen[key] = f
    return list(seen.values())


