@dataclass
class FillRecord:
    """Single execution fill extracted from a Sierra Chart binary log."""
    timestamp      : str            = ""
    ts_val         : float          = 0.0
    account        : str            = ""
    symbol         : str            = ""
    base_symbol    : str            = ""
    side           : str            = ""
    price          : float          = 0.0
    quantity       : int            = 1
    note           : str            = ""
    msgtxt         : str            = ""
    open_close     : str            = ""
    position_after : Optional[int]  = None
    order_id       : str            = ""
    position_order : int            = 999_999
    suggests_ghost : bool           = False

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> "FillRecord":
        """Construct a FillRecord from a raw parser dict."""
        raw_sym = d.get("symbol", "")
        return cls(
            timestamp      = d.get("timestamp", ""),
            ts_val         = float(d.get("ts_val") or 0.0),
            account        = d.get("account_name", d.get("account", "")),
            symbol         = raw_sym,
            base_symbol    = _base_symbol(raw_sym),
            side           = d.get("side", ""),
            price          = float(d.get("price") or 0.0),
            quantity       = int(d.get("quantity") or 1),
            note           = d.get("note", ""),
            msgtxt         = d.get("msgtxt", ""),
            open_close     = d.get("open_close", ""),
            position_after = d.get("position_after"),
            order_id       = str(d.get("order_id") or d.get("internal_order_id") or ""),
            position_order = int(d.get("_position_order") or 999_999),
            suggests_ghost = bool(d.get("suggests_ghost", False)),
        )

    def is_valid(self) -> bool:
        """Returns True if fill has minimum required fields."""
        return self.side in ("BUY", "SELL") and self.price > 0 and self.quantity > 0


@dataclass
class RoundTrip:
    """Completed entry-to-exit round-trip trade from the FIFO Resynchronizer."""
    account      : str   = ""
    symbol       : str   = ""
    base_symbol  : str   = ""
    direction    : str   = ""
    quantity     : int   = 1
    entry_time   : str   = ""
    exit_time    : str   = ""
    entry_price  : float = 0.0
    exit_price   : float = 0.0
    pnl_points   : float = 0.0
    pnl_dollars  : float = 0.0
    duration_min : float = 0.0
    entry_note   : str   = ""
    exit_note    : str   = ""

    def __repr__(self) -> str:
        sign = "+" if self.pnl_dollars >= 0 else ""
        return (f"RoundTrip({self.direction} {self.quantity}x {self.symbol} | "
                f"{self.entry_time[:16]} -> {self.exit_time[:16]} | "
                f"{sign}${self.pnl_dollars:.2f})")

    def as_dict(self) -> Dict:
        """Return JSON-safe dict representation."""
        return {
            "direction":    self.direction,
            "quantity":     self.quantity,
            "symbol":       self.symbol,
            "base_symbol":  self.base_symbol,
            "entry_time":   self.entry_time,
            "exit_time":    self.exit_time,
            "entry_price":  self.entry_price,
            "exit_price":   self.exit_price,
            "pnl_points":   round(self.pnl_points, 4),
            "pnl_dollars":  round(self.pnl_dollars, 2),
            "duration_min": round(self.duration_min, 1),
        }


@dataclass
class GFREResult:
    """Complete output of a GFRE processing run."""
    total_raw_fills     : int               = 0
    ghost_fills_dropped : int               = 0
    clean_fills         : int               = 0
    trades              : List[RoundTrip]   = field(default_factory=list)
    unpaired_fills      : List[FillRecord]  = field(default_factory=list)
    direction_flips     : int               = 0
    bypass_mode         : bool              = False
    integrity_ok        : bool              = True
    notes               : List[str]         = field(default_factory=list)

    def summary(self) -> str:
        """One-line human-readable summary of the run."""
        wins   = sum(1 for t in self.trades if t.pnl_dollars > 0)
        losses = len(self.trades) - wins
        net    = sum(t.pnl_dollars for t in self.trades)
        sign   = "+" if net >= 0 else ""
        return (
            f"GFRE | Raw: {self.total_raw_fills} | "
            f"Ghost dropped: {self.ghost_fills_dropped} | "
            f"Clean: {self.clean_fills} | "
            f"Trades: {len(self.trades)} ({wins}W/{losses}L) | "
            f"Net: {sign}${net:,.2f} | "
            f"Flips: {self.direction_flips} | "
            f"Integrity: {'PASS' if self.integrity_ok else 'FAIL'}"
        )

    def as_dict(self) -> Dict:
        """JSON-safe dict for API responses."""
        wins = sum(1 for t in self.trades if t.pnl_dollars > 0)
        net  = sum(t.pnl_dollars for t in self.trades)
        return {
            "total_raw_fills":      self.total_raw_fills,
            "ghost_fills_dropped":  self.ghost_fills_dropped,
            "clean_fills":          self.clean_fills,
            "total_trades":         len(self.trades),
            "winning_trades":       wins,
            "losing_trades":        len(self.trades) - wins,
            "net_pnl_dollars":      round(net, 2),
            "direction_flips":      self.direction_flips,
            "bypass_mode":          self.bypass_mode,
            "integrity_ok":         self.integrity_ok,
            "unpaired_fills":       len(self.unpaired_fills),
            "notes":                self.notes,
            "trades":               [t.as_dict() for t in self.trades],
        }


