def _base_symbol(raw: str) -> str:
    """Normalize a Sierra Chart raw symbol to its base instrument code."""
    s = raw.upper()
    overrides = {
        # Crude oil
        "CLN": "CL", "CLH": "CL", "CLQ": "CL", "CLU": "CL", "CLV": "CL", "CLZ": "CL",
        # Micro crude
        "MCL": "MCL",
        # S&P 500
        "ESM": "ES", "ESU": "ES", "ESZ": "ES", "ESH": "ES",
        # Micro S&P
        "MES": "MES",
        # Nasdaq-100
        "NQM": "NQ", "NQU": "NQ", "NQZ": "NQ", "NQH": "NQ",
        # Micro Nasdaq
        "MNQ": "MNQ",
        # Dow Jones
        "YMM": "YM", "YMU": "YM", "YMZ": "YM", "YMH": "YM",
        # Micro Dow
        "MYM": "MYM",
        # Russell 2000
        "RTY": "RTY", "RTYM": "RTY", "RTYU": "RTY", "RTYZ": "RTY", "RTYH": "RTY",
        # Micro Russell
        "M2K": "M2K", "M2KM": "M2K", "M2KU": "M2K", "M2KZ": "M2K", "M2KH": "M2K",
        # DAX
        "FDAX": "FDAX", "FDXM": "FDAX",
        # Gold
        "GCM": "GC", "GCZ": "GC", "GCQ": "GC", "GCJ": "GC", "GCV": "GC", "GCG": "GC",
        # Silver
        "SIK": "SI", "SIN": "SI", "SIU": "SI", "SIZ": "SI", "SIH": "SI",
        # Treasury bonds (ZB=30yr, ZN=10yr, ZF=5yr, ZT=2yr)
        "ZBM": "ZB", "ZBU": "ZB", "ZBZ": "ZB", "ZBH": "ZB",
        "ZNM": "ZN", "ZNU": "ZN", "ZNZ": "ZN", "ZNH": "ZN",
        "ZFM": "ZF", "ZFU": "ZF", "ZFZ": "ZF", "ZFH": "ZF",
        "ZTM": "ZT", "ZTU": "ZT", "ZTZ": "ZT", "ZTH": "ZT",
    }
    m = re.search(r"([A-Z]+)", s)
    if not m:
        return s
    head = m.group(1)
    if head[:3] in overrides:
        return overrides[head[:3]]
    for sym in sorted(SYMBOL_METADATA.keys(), key=len, reverse=True):
        if head.startswith(sym):
            return sym
    return head


def _multiplier(base_symbol: str) -> float:
    """Return the dollar-per-point contract multiplier for a base symbol."""
    return float(SYMBOL_METADATA.get(base_symbol, {}).get("multiplier", 1))


def _to_ny(ts_str: str) -> Optional[datetime.datetime]:
    """Parse ISO 8601 UTC string -> New York aware datetime. None on failure."""
    if not ts_str:
        return None
    try:
        dt = datetime.datetime.fromisoformat(ts_str.replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=datetime.timezone.utc)
        return dt.astimezone(NY_TZ)
    except Exception:
        return None


def _is_eod_exempt(ts_str: str) -> bool:
    """
    Return True if fill is in the EOD exempt window (16:55-17:05 NY).
    Session flatten events at day rollover often lack strategy tags.
    """
    ny = _to_ny(ts_str)
    if not ny:
        return False
    h, mn = ny.hour, ny.minute
    if h == EOD_WINDOW_OPEN_MIN[0] and mn >= EOD_WINDOW_OPEN_MIN[1]:
        return True
    if h == EOD_WINDOW_CLOSE_MIN[0] and mn <= EOD_WINDOW_CLOSE_MIN[1]:
        return True
    return False


def _has_strategy_tag(note: str, msgtxt: str) -> bool:
    """
    Return True if note (Tag 0x82) or message text contains a valid
    strategy attribution token.
    """
    if re.search(r"[A-Za-z0-9]", (note or "").strip()):
        return True
    ml = (msgtxt or "").lower()
    return any(p in ml for p in STRATEGY_TAG_PATTERNS)


